export const SelectorIA = () => {
  const [isDropdownOpen, setIsDropdownOpen] = useState(false);
  const [selectedAI, setSelectedAI] = useState('TIA');
  const dropdownRef = useRef(null);

  useEffect(() => {
    const handleClickOutside = (event) => {
      if (dropdownRef.current && !dropdownRef.current.contains(event.target)) {
        setIsDropdownOpen(false);
      }
    };
    document.addEventListener("mousedown", handleClickOutside);
    return () => document.removeEventListener("mousedown", handleClickOutside);
  }, []);

  const currentAI = AI_MODELS.find(ai => ai.id === selectedAI) || AI_MODELS[0];

  const handleAISelect = (aiId) => {
    setSelectedAI(aiId); 
    setIsDropdownOpen(false);
  };

  return (
    <div className="relative" ref={dropdownRef}>
      <button
        onClick={() => setIsDropdownOpen(!isDropdownOpen)}
        className="flex items-center gap-2 px-3 py-2 bg-bg-secondary hover:bg-bg-secondary-dark rounded-lg transition-colors border border-border-light"
        title={`Seleccionar IA: ${currentAI.name}`}
      >
        <currentAI.icon className={currentAI.color} />
        <span className="text-sm font-medium text-text-primary">{currentAI.name}</span>
        <ChevronDown className={`w-4 h-4 text-text-secondary transition-transform ${isDropdownOpen ? 'rotate-180' : ''}`} />
      </button>
      
      {isDropdownOpen && (
        <div className="absolute bottom-full mb-2 left-0 bg-bg-primary border border-border-light rounded-lg shadow-lg py-1 min-w-[140px] z-20">
          {AI_MODELS.map((ai) => (
            <button
              key={ai.id}
              onClick={() => handleAISelect(ai.id)}
              className={`w-full flex items-center gap-2 px-3 py-2 text-left hover:bg-bg-secondary transition-colors ${
                selectedAI === ai.id ? 'bg-bg-secondary' : ''
              }`}
            >
              <ai.icon className={ai.color} />
              <span className="text-sm font-medium text-text-primary">{ai.name}</span>
              {selectedAI === ai.id && (
                <div className="w-2 h-2 bg-green-500 rounded-full ml-auto" />
              )}
            </button>
          ))}
        </div>
      )}
    </div>
  );
};

export default SelectorIA;